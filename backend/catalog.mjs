export const city = (code) => cities.find((c) => c.code === code);
export const dateInShanghai = (ms) =>
  new Date(ms + 8 * 3600000).toISOString().slice(0, 10);
export const hash = (text) =>
  [...text].reduce((n, c) => (n * 31 + c.charCodeAt(0)) >>> 0, 7);
export function schedule(from, to, date) {
  const a = city(from),
    b = city(to),
    seed = hash(from + to + date);
  const duration = Math.max(
    75,
    Math.round(Math.hypot(a.x - b.x, a.y - b.y) * 3.2 + 60),
  );
  return airlines.map((airline, i) => {
    const hour = [7, 9, 12, 15, 19][i],
      minute = [15, 30, 5, 45, 20][i];
    const departure = `${date}T${String(hour).padStart(2, "0")}:${String(minute).padStart(2, "0")}:00+08:00`;
    return {
      id: `${from}-${to}-${date}-${i}`,
      from,
      to,
      date,
      airline,
      number: `${airline.code}${1100 + (seed % 6000) + i * 13}`,
      departure,
      arrival: new Date(Date.parse(departure) + duration * 60000).toISOString(),
      duration,
      base: 280 + (seed % 220) + i * 81,
      seats: 12 + i * 6,
      aircraft: i % 2 ? "Airbus A320" : "Boeing 737-800",
    };
  });
}
